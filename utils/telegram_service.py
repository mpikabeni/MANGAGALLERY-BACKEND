"""Manga Gallery FR - Telegram Bot logic.

Shared by the webhook route (routes/telegram.py) and the standalone runner (bot.py).
It talks to the Bot HTTP API directly (no extra dependency) and never touches the database,
so bot.py can run on its own.

Rule: before the mini app is offered, the user MUST be a member of the Nexa channel.
"""
import hashlib
import html
import json
import logging
import time
from urllib import error, request

from config import Config

log = logging.getLogger("mgfr.bot")

CALLBACK_VERIFY = "nx:verify"
_MEMBER_CACHE = {}          # user_id -> expiry (only positive answers are cached)
_CACHE_TTL = 60
_OK_STATUSES = {"creator", "administrator", "member"}


class TelegramError(RuntimeError):
    pass


def tg_call(method, payload=None, timeout=15):
    token = Config.TELEGRAM_BOT_TOKEN
    if not token:
        raise TelegramError("TELEGRAM_BOT_TOKEN is not configured")
    req = request.Request(
        f"https://api.telegram.org/bot{token}/{method}",
        data=json.dumps(payload or {}).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with request.urlopen(req, timeout=timeout) as resp:
            data = json.loads(resp.read().decode("utf-8"))
    except error.HTTPError as exc:  # Telegram answers 4xx with a JSON body
        try:
            data = json.loads(exc.read().decode("utf-8"))
        except Exception:
            raise TelegramError(f"Telegram HTTP {exc.code}") from exc
    except (error.URLError, TimeoutError, OSError) as exc:
        raise TelegramError("Telegram API unavailable") from exc
    if not data.get("ok"):
        raise TelegramError(data.get("description", "Telegram API error"))
    return data.get("result")


# ------------------------------------------------------------------ webhook
def webhook_secret_token():
    """Value sent to Telegram as `secret_token` and expected back in X-Telegram-Bot-Api-Secret-Token.

    Telegram only accepts A-Z a-z 0-9 _ - (1..256 chars). Secrets generated by hosting platforms are often
    base64 (with + / =) and are silently refused, so the webhook never gets registered and /start stays mute.
    We therefore derive a safe hex token from TELEGRAM_WEBHOOK_SECRET.
    """
    raw = Config.TELEGRAM_WEBHOOK_SECRET
    return hashlib.sha256(("mgfr-webhook:" + raw).encode("utf-8")).hexdigest() if raw else ""


def webhook_url():
    return Config.PUBLIC_BACKEND_URL.rstrip("/") + "/api/telegram/webhook"


def ensure_webhook():
    """(Re)register the webhook. Idempotent: Telegram simply replaces the previous registration."""
    if not (Config.TELEGRAM_BOT_TOKEN and Config.PUBLIC_BACKEND_URL.startswith("https://") and Config.TELEGRAM_WEBHOOK_SECRET):
        raise TelegramError("TELEGRAM_BOT_TOKEN, PUBLIC_BACKEND_URL (https) et TELEGRAM_WEBHOOK_SECRET sont requis")
    tg_call("setWebhook", {"url": webhook_url(), "secret_token": webhook_secret_token(),
                           "allowed_updates": ["message", "callback_query"], "drop_pending_updates": False})
    return webhook_url()


def setup_bot():
    """Commands (FR/EN) + the menu button that opens the mini app."""
    tg_call("setMyCommands", {"commands": [
        {"command": "start", "description": "Open " + Config.APP_NAME},
        {"command": "help", "description": "Help"},
        {"command": "version", "description": "Version"}]})
    tg_call("setMyCommands", {"language_code": "fr", "commands": [
        {"command": "start", "description": "Ouvrir " + Config.APP_NAME},
        {"command": "help", "description": "Aide"},
        {"command": "version", "description": "Version"}]})
    if Config.TELEGRAM_MINI_APP_URL.startswith("https://"):
        tg_call("setChatMenuButton", {"menu_button": {"type": "web_app", "text": Config.APP_NAME,
                                                       "web_app": {"url": Config.TELEGRAM_MINI_APP_URL}}})


def diagnose():
    """Non-sensitive status used by /api/telegram/health and `bot.py --info`."""
    out = {"token_configured": bool(Config.TELEGRAM_BOT_TOKEN), "webhook_secret_configured": bool(Config.TELEGRAM_WEBHOOK_SECRET),
           "public_backend_url": Config.PUBLIC_BACKEND_URL, "mini_app_url": Config.TELEGRAM_MINI_APP_URL,
           "channel_gate": Config.CHANNEL_GATE, "channel": channel_username() if Config.CHANNEL_GATE else None,
           "problems": []}
    if not out["token_configured"]:
        out["problems"].append("TELEGRAM_BOT_TOKEN manquant")
        return out
    try:
        me = tg_call("getMe")
        out["bot_username"] = me.get("username")
        info = tg_call("getWebhookInfo")
        out["webhook_url"] = info.get("url") or None
        out["webhook_ok"] = info.get("url") == webhook_url()
        out["pending_updates"] = info.get("pending_update_count", 0)
        out["last_error"] = info.get("last_error_message")
        if not out["webhook_ok"]:
            out["problems"].append("Webhook non enregistré sur " + webhook_url())
        if info.get("last_error_message"):
            out["problems"].append("Dernière erreur Telegram : " + info["last_error_message"])
        if Config.CHANNEL_GATE:
            try:
                member = tg_call("getChatMember", {"chat_id": channel_username(), "user_id": me["id"]})
                out["bot_channel_status"] = member.get("status")
                if member.get("status") != "administrator":
                    out["problems"].append("Le bot doit être ADMINISTRATEUR du canal " + channel_username())
            except TelegramError as exc:
                out["problems"].append(f"Canal {channel_username()} illisible : {exc}")
    except TelegramError as exc:
        out["problems"].append(str(exc))
    return out


# ------------------------------------------------------------------ channel membership
def channel_username():
    return Config.REQUIRED_CHANNEL if Config.REQUIRED_CHANNEL.startswith("@") else "@" + Config.REQUIRED_CHANNEL


def channel_url():
    return "https://t.me/" + channel_username().lstrip("@")


def is_channel_member(user_id, use_cache=True):
    """True if the user joined the required channel.

    Raises TelegramError if Telegram cannot answer (for example the bot is not an admin of the
    channel). The caller must fail closed: no answer means no access.
    """
    if not Config.CHANNEL_GATE:
        return True
    now = time.time()
    if use_cache and _MEMBER_CACHE.get(user_id, 0) > now:
        return True
    result = tg_call("getChatMember", {"chat_id": channel_username(), "user_id": int(user_id)})
    status = (result or {}).get("status")
    ok = status in _OK_STATUSES or (status == "restricted" and (result or {}).get("is_member"))
    if ok:
        _MEMBER_CACHE[user_id] = now + _CACHE_TTL
    else:
        _MEMBER_CACHE.pop(user_id, None)
    return bool(ok)


def is_owner(user_id):
    return bool(Config.ADMIN_TELEGRAM_ID) and int(user_id) == Config.ADMIN_TELEGRAM_ID


