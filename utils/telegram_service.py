def _lang(tg_user):
    code = (tg_user.get("language_code") or "en").lower()
    return "fr" if code.startswith("fr") else "en"


def _t(lang, key, **kw):
    return TEXTS[lang][key].format(channel=channel_username(), version=Config.APP_VERSION, **kw)


# ------------------------------------------------------------------ messages
def _send(chat_id, text, markup=None):
    payload = {"chat_id": chat_id, "text": text, "parse_mode": "HTML", "disable_web_page_preview": True}
    if markup:
        payload["reply_markup"] = markup
    return tg_call("sendMessage", payload)


def send_gate(chat_id, lang):
    markup = {"inline_keyboard": [
        [{"text": _t(lang, "join"), "url": channel_url()}],
        [{"text": _t(lang, "joined"), "callback_data": CALLBACK_VERIFY}],
    ]}
    _send(chat_id, f"<b>{_t(lang, 'gate_title')}</b>\n\n{_t(lang, 'gate_body')}", markup)


def send_welcome(chat_id, tg_user, lang):
    name = html.escape(tg_user.get("first_name") or tg_user.get("username") or "")
    intro = "welcome_intro_gate" if Config.CHANNEL_GATE else "welcome_intro_open"
    text = (f"<b>{_t(lang, 'welcome_title', name=name)}</b>\n\n{_t(lang, intro)}\n\n{_t(lang, 'welcome_main')}")
    url = Config.TELEGRAM_MINI_APP_URL
    if not url.startswith("https://"):
        _send(chat_id, text + "\n\n" + _t(lang, "no_url"))
        return
    _send(chat_id, text, {"inline_keyboard": [
        [{"text": _t(lang, "open"), "web_app": {"url": url}}],
        [{"text": _t(lang, "channel_btn"), "url": channel_url()}],
    ]})


def _allowed(user_id):
    return is_owner(user_id) or not Config.CHANNEL_GATE or is_channel_member(user_id, use_cache=False)


def _start_flow(chat_id, tg_user):
    lang = _lang(tg_user)
    try:
        if _allowed(tg_user["id"]):
            send_welcome(chat_id, tg_user, lang)
        else:
            send_gate(chat_id, lang)
    except TelegramError:
        log.exception("Channel membership check failed (is the bot an admin of %s ?)", channel_username())
        try:
            _send(chat_id, _t(lang, "error"))
        except TelegramError:
            log.exception("Could not even send the error message")


def handle_update(update):
    if not isinstance(update, dict):
        return

    cb = update.get("callback_query")
    if cb:
        tg_user = cb.get("from") or {}
        msg = cb.get("message") or {}
        chat_id = (msg.get("chat") or {}).get("id") or tg_user.get("id")
        lang = _lang(tg_user)
        if cb.get("data") == CALLBACK_VERIFY and tg_user.get("id"):
            try:
                if _allowed(tg_user["id"]):
                    tg_call("answerCallbackQuery", {"callback_query_id": cb["id"]})
                    send_welcome(chat_id, tg_user, lang)
                else:
                    tg_call("answerCallbackQuery", {"callback_query_id": cb["id"],
                                                    "text": _t(lang, "not_yet"), "show_alert": True})
            except TelegramError:
                log.exception("verify callback failed")
                try:
                    tg_call("answerCallbackQuery", {"callback_query_id": cb["id"],
                                                    "text": _t(lang, "error"), "show_alert": True})
                except TelegramError:
                    pass
        return

    message = update.get("message") or {}
    tg_user = message.get("from") or {}
    chat = message.get("chat") or {}
    if not tg_user.get("id") or chat.get("type") != "private":
        return
    text = (message.get("text") or "").strip()
    command = text.split()[0].split("@")[0].lower() if text.startswith("/") else ""
    lang = _lang(tg_user)

    if command == "/start":
        _start_flow(chat["id"], tg_user)
    elif command == "/help":
        _send(chat["id"], _t(lang, "help"))
    elif command == "/version":
        _send(chat["id"], _t(lang, "version"))
